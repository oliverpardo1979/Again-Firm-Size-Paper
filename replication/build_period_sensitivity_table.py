"""Render the endpoint-window comparison from the two validated joint models."""
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
old = pd.read_csv(ROOT / 'replication/salaried_extensions_output/endpoint_changes.csv')
new = pd.read_csv(ROOT / 'replication/period_sensitivity_output/endpoint_changes.csv')
lines = [r'% Generated by replication/build_period_sensitivity_table.py.',
         r'\begin{table}[p]', r'  \centering',
         r'  \caption{Sensitivity of endpoint changes to the starting year}',
         r'  \label{tab:period-sensitivity-2010}', r'  \small',
         r'  \setlength{\tabcolsep}{5pt}',
         r'  \begin{tabular}{llrrrrr}', r'    \toprule',
         r'    Sample & Status & Window & Initial (\%) & 2025 (\%) & $p$ (SD) & $p$ (S) \\',
         r'    \midrule']
for sample, label in [('All', 'Full'), ('Salaried', 'Salaried')]:
    for group in ['Formal', 'Informal']:
        for start, data in [(2008, old), (2010, new)]:
            rows = data[(data['sample'] == sample) & (data['reference'] == 'Solo')
                        & (data['size'] == '101+') & (data['group'] == group)]
            a = rows[rows.clustering == 'Sector-department'].iloc[0]
            b = rows[rows.clustering == 'Sector'].iloc[0]
            lines.append(f'    {label} & {group} & {start}--2025 & {a[f"premium_{start}"]:.1f}'
                         f' & {a.premium_2025:.1f} & {a["p.value"]:.4f} & {b["p.value"]:.4f}' + r' \\')
        if group == 'Formal':
            lines.append(r'    \addlinespace')
    if sample == 'All':
        lines.append(r'    \midrule')
lines += [r'    \bottomrule', r'  \end{tabular}', r'  \vspace{0.4em}',
          r'  \begin{minipage}{0.98\textwidth}', r'    \footnotesize',
          r'    Notes: The premium compares 101+ with solo workers of the same formality status. '
          r'Equation~(\ref{eq:preferred-dynamics}) is estimated jointly for each pair of endpoint years, '
          r'allowing all slopes to vary by year. Two-sided tests concern the change in the log-wage contrast, '
          r'not the significance of either endpoint level. SD denotes sector-department clustering and S sector clustering.',
          r'  \end{minipage}', r'\end{table}']
(ROOT / 'Paper/sections/period_sensitivity_table.tex').write_text('\n'.join(lines) + '\n', encoding='utf-8')
print('Generated period_sensitivity_table.tex from validated endpoint outputs.')
